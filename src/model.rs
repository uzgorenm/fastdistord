pub enum Command {
    StartMicTest,
    StopMicTest,
    PlayMicTest,
    SetProcessing(crate::audio_processing::ProcessingOptions),
    SetParticipantVolume {
        user_id: u64,
        volume: f32,
    },
    AnswerIncoming {
        channel: u64,
        generation: u64,
    },
    DeclineIncoming {
        channel: u64,
        generation: u64,
    },
    RequestNotificationPermission,
    SetDesktopNotifications(bool),
    LoadOlderMessages,
    ReplyMessage {
        channel_id: u64,
        message_id: u64,
        content: String,
    },
    EditMessage {
        channel_id: u64,
        message_id: u64,
        content: String,
    },
    ReactMessage {
        channel_id: u64,
        message_id: u64,
        emoji: String,
    },
    MarkChannelRead {
        channel_id: u64,
        message_id: u64,
    },
    CheckForUpdates,
    SetUpdateChecks(bool),
    SetAppearance(crate::preferences::Appearance),
    SetShortcuts(crate::shortcuts::ShortcutConfig),
    Connect {
        token: String,
        risk_accepted: bool,
        remember: bool,
    },
    #[cfg(target_os = "macos")]
    ConnectSaved {
        risk_accepted: bool,
    },
    Logout,
    Reconnect,
    RefreshSocial,
    OpenDm(u64),
    SelectDm(u64),
    CallDm(u64),
    SelectGuild(u64),
    SelectTextChannel(u64),
    RefreshMessages,
    SendMessage {
        channel_id: u64,
        content: String,
    },
    Join {
        guild_id: u64,
        channel_id: u64,
    },
    Leave,
    SetMuted(bool),
    SetDeafened(bool),
    SetPtt(bool),
    SetCallSounds(bool),
    SetSoundVolume(f32),
    SetOutputVolume(f32),
    RefreshDevices,
    SetDevices {
        input: Option<String>,
        output: Option<String>,
    },
    SetUiRepaint(Arc<dyn Fn() + Send + Sync>),
    SetUiVisible(bool),
    Quit,
}
